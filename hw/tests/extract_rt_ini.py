"""Extracts the game runtime's [link] reader (trim_ + rt_sio_read_ini from recomp/runtime/rt_sio.c) into a
standalone C file so the parity test can run the REAL runtime code next to hw/config_ini.c.

usage: python extract_rt_ini.py <rt_sio.c> <out.c>
Fails (exit 1) if the functions cannot be found, so a refactor on the runtime side shows up as a test failure."""
import re
import sys


def grab(src, start_pat):
    m = re.search(start_pat, src)
    if not m:
        raise SystemExit("extract_rt_ini: cannot find %r in %s" % (start_pat, sys.argv[1]))
    i = src.index("{", m.start())
    depth = 0
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[m.start():j + 1]
    raise SystemExit("extract_rt_ini: unbalanced braces after %r" % start_pat)


def main():
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    trim = grab(src, r"static char \*trim_\(char \*s\)")
    rd = grab(src, r"void rt_sio_read_ini\(const char \*path, char \*mode, int \*players, int \*port, char \*host, int \*delay\)")
    out = ("/* generated by hw/tests/extract_rt_ini.py from recomp/runtime/rt_sio.c - do not edit */\n"
           "#include <stdio.h>\n#include <string.h>\n#include <stdlib.h>\n#include <ctype.h>\n\n"
           + trim + "\n\n" + rd + "\n")
    open(sys.argv[2], "w", encoding="utf-8").write(out)
    print("extracted %d + %d chars" % (len(trim), len(rd)))


main()
