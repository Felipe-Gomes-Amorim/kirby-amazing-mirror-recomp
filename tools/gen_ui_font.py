"""Bake the launcher fonts (Pixelify Sans, Silkscreen; SIL OFL, see hw/fonts/OFL.txt) into hw/ui_font_data.c.

  pip install pillow fonttools brotli          (only needed to REGENERATE; the generated .c is committed)
  python tools/gen_ui_font.py

Every font is rendered once at a fixed pixel size, 1 bit per pixel (no anti-aliasing: it stays a pixel font), for
ASCII 32..126 and Latin-1 160..255 (accents!). The launcher turns the bitmaps into one texture atlas per font.
Keep FONTS in step with the UF_* enum in hw/ui_font.h.
"""
import os
import sys

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIX = os.path.join(ROOT, 'hw', 'fonts', 'PixelifySans-Latin.woff2')
SILK = os.path.join(ROOT, 'hw', 'fonts', 'Silkscreen-Latin.woff2')

# (enum name, source, pixel size, weight or None)
FONTS = [
    ('UF_LBL', SILK, 10, None),      # Silkscreen labels (CAPS)
    ('UF_S11', PIX, 11, 400),        # descriptions
    ('UF_S12', PIX, 12, 400),        # chips, tags, lobby rows
    ('UF_B13', PIX, 13, 400),        # body
    ('UF_S15', PIX, 15, 600),        # card titles, nav titles
    ('UF_S18', PIX, 18, 600),        # PLAY
    ('UF_T22', PIX, 22, 600),        # page titles
    ('UF_HERO', PIX, 60, 600),       # KIRBY RECOMP
]
CODES = list(range(32, 127)) + list(range(160, 256))


def load(src, tmp):
    t = TTFont(src)
    t.flavor = None
    path = os.path.join(tmp, os.path.basename(src) + '.ttf')
    t.save(path)
    return path


def bake(ttf, px, wght):
    f = ImageFont.truetype(ttf, px)
    if wght:
        f.set_variation_by_axes([wght])
    asc, desc = f.getmetrics()
    glyphs, bits = [], bytearray()
    for cp in CODES:
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        if cp == 32:
            adv = max(adv, int(round(px * 0.33)))      # the font's own space is too tight at 1 px resolution
        W, H = px * 3, px * 3
        im = Image.new('L', (W, H), 0)
        ImageDraw.Draw(im).text((px, px * 2), ch, font=f, fill=255, anchor='ls', fontmode='1')
        bbox = im.getbbox()
        if not bbox:
            glyphs.append((len(bits), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        off = len(bits)
        for y in range(h):
            # packed LSB-first per byte, rows padded to whole bytes
            nb = (w + 7) // 8
            rb = bytearray(nb)
            for x in range(w):
                if im.getpixel((x0 + x, y0 + y)) >= 128:
                    rb[x // 8] |= 1 << (x % 8)
            bits += rb
        glyphs.append((off, w, h, x0 - px, y0 - px * 2, adv))
    return asc, desc, glyphs, bits


def main():
    import tempfile
    tmp = tempfile.mkdtemp()
    ttfs = {PIX: load(PIX, tmp), SILK: load(SILK, tmp)}
    out = ['/* GENERATED by tools/gen_ui_font.py - do not edit. Pixelify Sans / Silkscreen (SIL OFL 1.1, hw/fonts/OFL.txt). */',
           '#include "ui_font.h"', '']
    tabs = []
    for name, src, px, wght in FONTS:
        asc, desc, glyphs, bits = bake(ttfs[src], px, wght)
        sym = name.lower()
        out.append('static const unsigned char %s_bits[] = {' % sym)
        for i in range(0, len(bits), 24):
            out.append('    ' + ','.join(str(b) for b in bits[i:i + 24]) + ',')
        if not bits:
            out.append('    0')
        out.append('};')
        out.append('static const UiGlyph %s_glyphs[%d] = {' % (sym, len(glyphs)))
        for g in glyphs:
            out.append('    {%d,%d,%d,%d,%d,%d},' % g)
        out.append('};')
        out.append('')
        tabs.append('    [%s] = { %d, %d, %d, %s_glyphs, %s_bits },' % (name, px, asc, desc, sym, sym))
    out.append('const UiFont ui_fonts[UF_COUNT] = {')
    out += tabs
    out.append('};')
    path = os.path.join(ROOT, 'hw', 'ui_font_data.c')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', path, os.path.getsize(path), 'bytes')


if __name__ == '__main__':
    sys.exit(main())
